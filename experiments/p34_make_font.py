"""Generate a bitmap font header for the on-board C panel program.

The board has no Python and no font stack, so the glyphs have to travel as data.
Rendering them here with Pillow and emitting a C header keeps the board code to a
plain bit-blit and means the on-board text matches what the host previews look
like.

Output: embedded/arm_panel/font8x12.h

The glyph set is printable ASCII 32..126. Each glyph is 8 pixels wide and 12 tall
so a row fits in one byte; a set bit means "ink".
"""

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "embedded" / "arm_panel" / "font8x12.h"

WIDTH = 8
HEIGHT = 12
FIRST = 32
LAST = 126
POINT = 11          # font size; small enough to keep 12 rows legible


def render_glyphs() -> dict[int, list[int]]:
    try:
        font = ImageFont.load_default(size=POINT)
    except TypeError:                                          # older Pillow
        font = ImageFont.load_default()

    glyphs: dict[int, list[int]] = {}
    for code in range(FIRST, LAST + 1):
        image = Image.new("L", (WIDTH, HEIGHT), 0)
        draw = ImageDraw.Draw(image)
        draw.text((0, 0), chr(code), fill=255, font=font)
        rows = []
        for y in range(HEIGHT):
            bits = 0
            for x in range(WIDTH):
                if image.getpixel((x, y)) > 96:
                    bits |= 1 << (7 - x)
            rows.append(bits)
        glyphs[code] = rows
    return glyphs


def main() -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:                                          # noqa: BLE001
        pass

    glyphs = render_glyphs()
    filled = sum(1 for rows in glyphs.values() if any(rows))
    if filled < 60:
        print(f"refusing to write: only {filled} glyphs have ink (font failed to render)")
        return 2

    lines = [
        "/* Generated by experiments/p34_make_font.py - do not edit by hand. */",
        "#ifndef ARM_PANEL_FONT8X12_H",
        "#define ARM_PANEL_FONT8X12_H",
        "",
        f"#define FONT_FIRST {FIRST}",
        f"#define FONT_LAST  {LAST}",
        f"#define FONT_W     {WIDTH}",
        f"#define FONT_H     {HEIGHT}",
        "",
        "/* One byte per row, MSB is the leftmost pixel. */",
        f"static const unsigned char FONT_DATA[{LAST - FIRST + 1}][{HEIGHT}] = {{",
    ]
    for code in range(FIRST, LAST + 1):
        rows = ", ".join(f"0x{b:02x}" for b in glyphs[code])
        printable = chr(code) if 32 <= code < 127 else "?"
        lines.append(f"    {{ {rows} }},  /* {code} '{printable}' */")
    lines.append("};")
    lines.append("")
    lines.append("#endif")
    lines.append("")

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_bytes(("\n".join(lines)).encode("utf-8"))
    print(f"wrote {TARGET.relative_to(ROOT)}: {filled} glyphs with ink, {WIDTH}x{HEIGHT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
