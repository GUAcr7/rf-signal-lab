"""Bundle explicit verified TX candidates without automatic RF startup."""
import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import shlex
import shutil
import tarfile

from rfsig.tx_package import file_hash, link_plan_template, verify_tx_package

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--package", type=Path, action="append", required=True)
    parser.add_argument("--native-preparation", type=Path, required=True)
    parser.add_argument("--mock-report", type=Path, required=True)
    args = parser.parse_args()
    native_dir = args.native_preparation.resolve()
    native = json.loads((native_dir / "report.json").read_text(encoding="utf-8"))
    mock = json.loads(args.mock_report.read_text(encoding="utf-8"))
    source = ROOT / "embedded/arm_tx_source/arm_tx_source.c"
    if file_hash(source) != native["source_sha256"]:
        raise ValueError("Current native source differs from prepared binary")
    c_source_key = "embedded/arm_tx_source/arm_tx_source.c"
    if (mock.get("status") != "passed_host_mock_only" or mock.get("kind") != "HOST_IN_MEMORY_MOCK_ONLY_NOT_RF"
        or mock.get("real_device_access") is not False or mock.get("real_rf_transmission") is not False
        or mock.get("sources_unchanged_during_test") is not True
        or mock.get("passed_count") != 34 or mock.get("case_count") != 34
        or not all(case.get("passed") is True for case in mock.get("cases", []))
        or not {"reject-tx_dma_rate_missing", "reject-tx_dma_rate_mismatch"}.issubset({case.get("name") for case in mock.get("cases", [])})
        or mock.get("source_sha256_before", {}).get(c_source_key) != native["source_sha256"]
        or mock.get("source_sha256_after", {}).get(c_source_key) != native["source_sha256"]):
        raise ValueError("Matching native mock evidence is required")
    archive = Path(native["archive"])
    if file_hash(archive) != native["archive_sha256"]:
        raise ValueError("Prepared archive changed")
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S%fZ")
    out = ROOT / "results" / ("p12-source-delivery-" + stamp)
    prefix = "p201-source-" + stamp
    bundle = out / prefix
    (bundle / "bin").mkdir(parents=True)
    original_bin = native_dir / native["prefix"] / "bin/arm-tx-source"
    if file_hash(original_bin) != native["binary_sha256"]:
        raise ValueError("Prepared executable changed")
    shutil.copy2(original_bin, bundle / "bin/arm-tx-source")
    shutil.copy2(source, bundle / "arm_tx_source.c")
    for name in ("iio.h", "source.json"):
        shutil.copy2(native_dir / native["prefix"] / name, bundle / name)
    check_lines = ["#!/bin/sh", "set -eu", 'cd "$(dirname "$0")"',
                   "sha256sum -c SHA256SUMS", "./bin/arm-tx-source --sha256-selftest"]
    packages = []
    for directory in args.package:
        directory = directory.resolve()
        verification = verify_tx_package(directory)
        manifest = json.loads((directory / "manifest.json").read_text(encoding="utf-8"))
        profile = manifest["profile"]
        if profile not in {"existing30m72", "planned4m250k", "planned4m125k"}:
            raise ValueError("Only explicit project profiles may be delivered")
        target = bundle / "waveforms" / profile
        target.mkdir(parents=True, exist_ok=False)
        shutil.copy2(directory / "manifest.json", target / "manifest.json")
        (target / "link-review.INCOMPLETE.json").write_text(json.dumps(link_plan_template(directory), indent=2) + "\n", encoding="utf-8")
        for item in manifest["waveforms"]:
            shutil.copy2(directory / item["raw_file"], target / item["raw_file"])
            # This generated shell uses only fixed profile/name basenames and
            # decimal/hash fields generated by our verifier, never arbitrary text.
            check_lines.append(" ".join(shlex.quote(str(arg)) for arg in ["./bin/arm-tx-source", "--check",
                f"waveforms/{profile}/{item['raw_file']}", item["sample_count"], item["raw_sha256"]]))
        packages.append(dict(profile=profile, source=str(directory), manifest_sha256=verification["package_sha256"]))
    check_lines.append("echo CHECK_ONLY_FINISHED_NO_IIO_NO_RF")
    (bundle / "CHECK-ONLY.sh").write_text("\n".join(check_lines) + "\n", encoding="ascii", newline="\n")
    (bundle / "INSPECT-ONLY.sh").write_text('#!/bin/sh\nset -eu\ncd "$(dirname "$0")"\nsha256sum -c SHA256SUMS\n./bin/arm-tx-source --inspect\n', encoding="ascii", newline="\n")
    shutil.copy2(ROOT / "docs/design/two-board-rf-link.md", bundle / "TWO-BOARD-PLAN.md")
    (bundle / "README.txt").write_text(
        "P201 finite-session source CANDIDATE. NOT RF-VERIFIED.\n"
        "Target original PUZHI PZSDR P201, local libiio 0.24; not the new TLZ7xH receiver.\n"
        "CHECK-ONLY.sh only hashes files and checks digital bytes. It never opens IIO.\n"
        "INSPECT-ONLY.sh reads existing local IIO attributes without buffers or writes.\n"
        "No auto-transmit script, boot service, firmware or RF-setting script is included.\n"
        "Never run the RF command until actual connector power, attenuation and wiring are reviewed.\n"
        "Link-review templates are intentionally INCOMPLETE and rejected.\n"
        "30.72 MS/s is historical, not a fresh board readback. 4 MS/s profiles are plans only.\n"
        "The native guard requires TX DMA rate = PHY rate = file rate (FPGA interpolation bypass).\n"
        "One source wave is repeated; repeated slices do not form independent train/test data.\n"
        "Software deadline (<=60 s), SIGTERM and cleanup were checked on a HOST MOCK only.\n"
        "Digital zero/buffer release do not prove RF silence or remove LO leakage.\n"
        "Archive must be copied to a NEW board /tmp directory and sha256 checked.\n"
        "BusyBox tar on the original board does not support -z: this archive is plain .tar.\n",
        encoding="ascii", newline="\n")
    members = [path for path in sorted(bundle.rglob("*")) if path.is_file()]
    (bundle / "SHA256SUMS").write_text("".join(file_hash(p) + "  " + p.relative_to(bundle).as_posix() + "\n" for p in members), encoding="ascii", newline="\n")
    archive = out / (prefix + ".tar")
    with tarfile.open(archive, "w") as tar:
        for path in sorted(bundle.rglob("*")):
            if path.is_file():
                info = tar.gettarinfo(str(path), prefix + "/" + path.relative_to(bundle).as_posix())
                info.mode = 0o755 if path.parent.name == "bin" or path.suffix == ".sh" else 0o644
                with path.open("rb") as stream:
                    tar.addfile(info, stream)
    report = dict(status="candidate_bundle_checksums_verified_actual_board_and_RF_pending",
                  archive=str(archive), archive_sha256=file_hash(archive), archive_bytes=archive.stat().st_size,
                  prefix=prefix, packages=packages, source_sha256=native["source_sha256"],
                  binary_sha256=native["binary_sha256"], native_preparation=str(native_dir),
                  mock_report=str(args.mock_report.resolve()), rf_transmitted=False,
                  board_files_written=False, auto_transmit_entry_included=False)
    (out / "report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(dict(output=str(out), **report)))


if __name__ == "__main__":
    main()
