"""Verify vendor byte invariants and packaged constraint references after migration."""
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest() if path.is_file() else None


def main():
    active = json.loads((ROOT / 'results/p29-active-build.json').read_text('utf-8'))
    work = Path(active['work'])
    initial = json.loads(Path(active['preparation']).read_text('utf-8'))
    changes = []
    checked = 0
    for group in ['vendor_rf_sources', 'staged_adi', 'staged_display']:
        for item in initial[group]:
            path = Path(item['path'])
            if sha(path) != item['sha256']:
                changes.append(dict(group=group, path=str(path)))
            checked += 1
    staged_rf_mismatches = []
    # Derive the source root from the fixed manifest path rather than a guessed
    # parent depth (manifest includes constraints/, hdl/, scripts/).
    original_rf_root = Path('D:/AD9361/AD9361/软件资料/Demo/hw/src')
    for item in initial['vendor_rf_sources']:
        relative = Path(item['path']).relative_to(original_rf_root)
        candidate = work / 'rf/src' / relative
        if relative.as_posix() == 'scripts/system_bd.tcl':
            continue  # archived, explicit Vivado version-guard migration only
        if sha(candidate) != item['sha256']:
            staged_rf_mismatches.append(str(candidate))
    display_source_mismatches = []
    display_sources_checked = 0
    variants = [work / 'display-v2', work / 'display-v3']
    if active.get('display_short_project'):
        variants.append(Path(active['display_short_project']).parent)
    for variant in variants:
        for item in initial['staged_display']:
            relative = Path(item['path']).relative_to(work / 'display')
            rel = relative.as_posix()
            if '.cache/' in rel or '/bd/' in rel or relative.suffix == '.xpr':
                continue
            candidate = variant / relative
            display_sources_checked += 1
            if sha(candidate) != item['sha256']:
                display_source_mismatches.append(str(candidate))
    allowed = {str(work / 'adi/library/scripts/adi_ip.tcl'),
               str(work / 'display/axi_video_display.xpr')}
    # The first exploratory display upgrade changed its copied BD; keep that
    # copy and raw evidence, while the final candidate is a separate directory.
    def generated_display_change(item):
        path = Path(item['path'])
        rel = path.relative_to(work / 'display').as_posix()
        # BD products are regenerated by Vivado. Handwritten module references,
        # top wrappers and board constraints outside bd/ must remain byte-identical.
        return ('.cache/' in rel or '/bd/' in rel or path.suffix == '.xpr')
    unexpected = [c for c in changes if c['path'] not in allowed and
                  not (c['group'] == 'staged_display' and generated_display_change(c))]
    ns = {'s': 'http://www.spiritconsortium.org/XMLSchema/SPIRIT/1685-2009'}
    constraints = []
    broken = []
    duplicates = []
    for ip in initial['custom_ips_dependency_order']:
        component = work / 'adi/library' / ip / 'component.xml'
        tree = ET.parse(component)
        for fileset in tree.findall('s:fileSets/s:fileSet', ns):
            seen = set()
            for file in fileset.findall('s:file', ns):
                name = file.findtext('s:name', namespaces=ns)
                if not name:
                    continue
                canonical = (component.parent / name).resolve()
                if str(canonical).lower() in seen:
                    duplicates.append(dict(ip=ip, fileset=fileset.findtext('s:name', namespaces=ns), path=str(canonical)))
                seen.add(str(canonical).lower())
                if not canonical.is_file():
                    broken.append(dict(ip=ip, path=str(canonical)))
                if canonical.suffix.lower() in {'.xdc', '.ttcl'}:
                    scopes = []
                    for elem in file.iter():
                        if elem.text and elem.text.startswith('SCOPED_TO_REF_'):
                            scopes.append(elem.text[len('SCOPED_TO_REF_'):])
                        if elem.tag.split('}')[-1].lower() == 'scoped_to_ref':
                            scopes.append(elem.text)
                        if any(str(v).upper() == 'SCOPED_TO_REF' for v in elem.attrib.values()):
                            scopes.append(''.join(elem.itertext()).strip())
                    constraints.append(dict(ip=ip, fileset=fileset.findtext('s:name', namespaces=ns),
                                            path=str(canonical), sha256=sha(canonical),
                                            scoped_to_ref=scopes))
    required = set()
    for ip in initial['custom_ips_dependency_order']:
        script = work / 'adi/library' / ip / f'{ip}_ip.tcl'
        for name in re.findall(r'"([^"\n]+\.(?:xdc|ttcl))"', script.read_text('utf-8-sig')):
            name = name.replace('$ad_hdl_dir', (work / 'adi').as_posix())
            required.add((ip, str((script.parent / name).resolve()).lower()))
    present = {(c['ip'], c['path'].lower()) for c in constraints}
    missing_scopes = [c for c in constraints if c['ip'] == 'axi_ad9361' and
                      Path(c['path']).suffix == '.xdc' and not c['scoped_to_ref']]
    record = dict(created_utc=datetime.now(timezone.utc).isoformat(), checked_files=checked,
                  original_source_or_archive_hashes_match=all(sha(Path(initial[k]['path'])) == initial[k]['sha256'] for k in ['adi_archive', 'display_archive']),
                  recorded_staged_changes=changes, unexpected_source_changes=unexpected,
                  staged_rf_hdl_constraints_mismatches=staged_rf_mismatches,
                  display_handwritten_sources_checked=display_sources_checked,
                  display_handwritten_source_mismatches=display_source_mismatches,
                  broken_component_files=broken, duplicate_files_in_same_fileset=duplicates,
                  constraints=constraints, missing_required_constraint_files=sorted(required-present),
                  missing_scopes=missing_scopes,
                  scope_note='scoped_to_ref captured from XML vendor extensions; inspect required scopes below',
                  board_operations=False)
    passed = (not unexpected and not staged_rf_mismatches and not display_source_mismatches and not broken and not duplicates and not missing_scopes and required <= present and
              record['original_source_or_archive_hashes_match'])
    record['status'] = 'passed' if passed else 'failed'
    out = ROOT / 'results' / datetime.now(timezone.utc).strftime('p29-source-verification-%Y%m%dT%H%M%SZ')
    out.mkdir(exist_ok=False)
    (out / 'report.json').write_text(json.dumps(record, indent=2) + '\n', encoding='utf-8')
    print(out)
    print(record['status'], 'files', checked, 'constraint entries', len(constraints),
          'unexpected', len(unexpected), 'broken', len(broken), 'duplicate', len(duplicates), 'missing', sorted(required-present))
    return 0 if passed else 1


if __name__ == '__main__':
    raise SystemExit(main())
